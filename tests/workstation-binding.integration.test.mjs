import 'reflect-metadata';
import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { PrismaClient } from '@prisma/client';
import { QueueService } from '../apps/api/dist/modules/queue/queue.service.js';
import { SchedulingService } from '../apps/api/dist/modules/scheduling/scheduling.service.js';
import { AuditService } from '../apps/api/dist/modules/audit/audit.service.js';
const url = process.env.WORKSTATION_TEST_DATABASE_URL;
test('persistent workstations, safe unbinding, administrator routing and concurrent calls', {skip: !url}, async () => {
  const parsed = new URL(url); assert.equal(parsed.hostname, '127.0.0.1'); assert.equal(parsed.port, '15488'); assert.match(parsed.pathname, /^\/workstation_qa_\d+$/);
  const db = new PrismaClient({datasources: {db: {url}}});
  try {
    const audit = new AuditService(db), scheduling = new SchedulingService(db, audit), queue = new QueueService(db, audit, null, scheduling);
    const org = await db.organization.create({data:{displayName:'Synthetic workstation QA'}});
    const office = await db.clinicOffice.create({data:{organizationId:org.id,name:'Synthetic clinic'}});
    const actor = await db.employee.create({data:{fullName:'Synthetic doctor'}});
    const deviceId = randomUUID(), otherDeviceId = randomUUID();
    const station = await queue.registerWorkstation({deviceId});
    const other = await queue.registerWorkstation({deviceId:otherDeviceId});
    let binding = await queue.updateWorkstation(station.id,{officeId:office.id,roomName:'Приёмная 1'},actor.id);
    const firstRoom = binding.roomId;
    assert.equal((await queue.registerWorkstation({deviceId})).roomId, firstRoom);
    await queue.updateWorkstation(other.id,{officeId:office.id,roomName:'Приёмная 2'},actor.id);
    const entry = await db.queueEntry.create({data:{ownerName:'Synthetic Visitor',animalNickname:'Synthetic pet'}});
    const called = await queue.startQueueEntry(entry.id,actor.id,{deviceId});
    assert.equal(called.room.name,'Приёмная 1');
    const screen = await queue.getQueueScreen();
    assert.equal(screen.called.find(x=>x.id===entry.id).roomName,'Приёмная 1');
    const repeated = await queue.startQueueEntry(entry.id,actor.id,{deviceId}); assert.equal(repeated.callCount,2);
    await assert.rejects(()=>queue.startQueueEntry(entry.id,actor.id,{deviceId:otherDeviceId}),/другой кабинет/);
    await queue.updateWorkstation(station.id,{roomId:null,isReception:false},actor.id);
    await assert.rejects(()=>queue.startQueueEntry(entry.id,actor.id,{deviceId}),/не привязано/);
    assert.equal((await db.queueEntry.findUnique({where:{id:entry.id}})).callCount,2);
    binding = await queue.updateWorkstation(station.id,{roomId:null,isReception:true},actor.id);
    assert.equal(binding.roomId,null);assert.equal(binding.isReception,true);
    const adminEntry = await db.queueEntry.create({data:{roomId:firstRoom}});
    assert.equal((await queue.startQueueEntry(adminEntry.id,actor.id,{deviceId})).roomId,firstRoom);
    const noRoom = await db.queueEntry.create({data:{}});
    await assert.rejects(()=>queue.startQueueEntry(noRoom.id,actor.id,{deviceId}),/Укажите кабинет/);
    await queue.updateWorkstation(station.id,{officeId:office.id,roomName:'Процедурная',isReception:false},actor.id);
    const concurrent = await db.queueEntry.create({data:{}});
    const results = await Promise.allSettled([queue.startQueueEntry(concurrent.id,actor.id,{deviceId}),queue.startQueueEntry(concurrent.id,actor.id,{deviceId:otherDeviceId})]);
    assert.equal(results.filter(x=>x.status==='fulfilled').length,1);
    assert.equal((await db.queueEntry.findUnique({where:{id:concurrent.id}})).callCount,1);
    binding = await queue.updateWorkstation(station.id,{officeId:office.id,roomName:'Стационар'},actor.id);
    assert.equal(binding.room.name,'Стационар');
    assert.equal((await queue.listWorkstations()).length,2);
    console.log('PASS persisted room, TV destination, repeat, unbind, administrator manual destination, concurrent call and all four clinical locations');
  } finally {await db.$disconnect();}
});
