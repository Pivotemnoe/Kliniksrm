test('device endpoints are bounded, account ownership cannot be overwritten, and explicit opt-out survives', async t => {
  const f = await fixture(t), d = await f.device(f.groomer), other = await f.device(f.otherGroomer);
  for (const endpoint of ['http://127.0.0.1/internal', 'https://127.0.0.1/private', 'https://fcm.googleapis.com.attacker.example/send', 'https://u:p@fcm.googleapis.com/send', 'https://fcm.googleapis.com:444/send', 'file:///etc/passwd']) assert.throws(() => validateGroomingPushEndpoint(endpoint));
  await assert.rejects(f.notices.subscribe(other.context, d.subscription), /другому сотруднику/);
  await f.notices.unsubscribe(other.context, d.subscription.endpoint);
  assert.equal((await f.notices.config(d.context)).devices.length, 1);
  await f.notices.unsubscribe(d.context, d.subscription.endpoint);
  assert.equal((await f.notices.config(d.context)).devices.length, 0);
  await f.prisma.session.deleteMany({ where: { id: { in: [d.session.id, other.session.id] } } });
});
test('revoking the trusted remote phone stops push even while its notification grant remains', async t => {
  const f = await fixture(t), d = await f.device(f.groomer);
  const organization = await f.prisma.organization.findFirstOrThrow();
  const previous = await f.prisma.remoteAccessPolicy.findUnique({ where: { organizationId: organization.id } });
  await f.prisma.remoteAccessPolicy.upsert({ where: { organizationId: organization.id }, create: { organizationId: organization.id, enabled: true }, update: { enabled: true } });
  const remote = await f.prisma.remoteAccessDevice.create({ data: { organizationId: organization.id, employeeId: f.groomer.id, tokenHash: randomUUID(), name: 'Синтетический телефон' } });
  t.after(async () => {
    await f.prisma.remoteAccessDevice.deleteMany({ where: { id: remote.id } });
    if (previous) await f.prisma.remoteAccessPolicy.update({ where: { id: previous.id }, data: { enabled: previous.enabled } });
    else await f.prisma.remoteAccessPolicy.deleteMany({ where: { organizationId: organization.id } });
  });
  await f.prisma.session.update({ where: { id: d.session.id }, data: { accessType: 'REMOTE', remoteDeviceId: remote.id } });
  await f.prisma.groomingPushSubscription.update({ where: { endpoint: d.subscription.endpoint }, data: { remoteDeviceId: remote.id } });
  await f.service.book(f.owner.id, input((await f.service.options(f.owner.id, f.options)).offers[0]));
  await f.prisma.remoteAccessDevice.update({ where: { id: remote.id }, data: { revokedAt: new Date() } });
  await f.notices.dispatch(); assert.equal(f.sent.length, 0);
  assert.equal(await f.prisma.groomingPushDelivery.count({ where: { subscription: { employeeId: f.groomer.id }, status: 'CANCELLED' } }), 1);
  await f.prisma.session.deleteMany({ where: { id: d.session.id } });
});
