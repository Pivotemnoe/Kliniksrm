test('staff service worker caches only the offline notice, sanitizes clicks and hides private push text', async () => {
  const events = {}, shown = [], opened = [], cached = [];
  const self = { location: { origin: 'https://staff.example.test' }, clients: { claim: async () => {}, matchAll: async () => [], openWindow: async url => opened.push(url) }, registration: { showNotification: async (...args) => shown.push(args), getNotifications: async () => [] }, skipWaiting: async () => {}, addEventListener: (name, handler) => { events[name] = handler; } };
  const caches = { open: async () => ({ add: async url => cached.push(url) }), keys: async () => [], match: async () => ({ offline: true }) };
  runInNewContext(await readFile(new URL('../apps/web/public/grooming/sw.js', import.meta.url), 'utf8'), { self, caches, URL, Response, fetch: async () => { throw Error('offline'); } });
  let pending; events.install({ waitUntil: promise => { pending = promise; } }); await pending;
  assert.deepEqual(cached, ['/grooming/offline.html']);
  events.push({ data: { json: () => ({ body: 'PRIVATE CLIENT DATA', url: 'https://attacker.example/', tag: 'grooming-staff:test' }) }, waitUntil: promise => { pending = promise; } }); await pending;
  assert.equal(shown[0][1].body.includes('PRIVATE'), false);
  events.notificationclick({ notification: { close() {}, data: { url: 'https://attacker.example/' } }, waitUntil: promise => { pending = promise; } }); await pending;
  assert.equal(opened[0], 'https://staff.example.test/grooming/notifications');
  const bookingUrl = 'https://staff.example.test/grooming/bookings?booking=synthetic-booking';
  self.clients.matchAll = async () => [{ url: 'https://staff.example.test/grooming/calendar', navigate: async () => { throw Error('A suspended Android page cannot navigate'); }, focus: async () => { throw Error('The old Android page cannot be focused'); } }];
  events.notificationclick({ notification: { close() {}, data: { url: bookingUrl } }, waitUntil: promise => { pending = promise; } }); await pending;
  assert.equal(opened[1], bookingUrl);
  self.clients.matchAll = async () => [{ url: bookingUrl, focus: async () => { throw Error('The old phone window was closed'); } }];
  events.notificationclick({ notification: { close() {}, data: { url: bookingUrl } }, waitUntil: promise => { pending = promise; } }); await pending;
  assert.equal(opened[2], bookingUrl);
  let focused = 0;
  self.clients.matchAll = async () => [{ url: bookingUrl, focus: async () => { focused += 1; } }];
  events.notificationclick({ notification: { close() {}, data: { url: bookingUrl } }, waitUntil: promise => { pending = promise; } }); await pending;
  assert.equal(focused, 1); assert.equal(opened.length, 3);
  const navigationOrder = [];
  const otherPage = { url: 'https://staff.example.test/grooming/calendar', focus: async () => { navigationOrder.push('focus'); return otherPage; }, navigate: async url => { navigationOrder.push('navigate'); assert.equal(url, bookingUrl); return { url }; } };
  self.clients.matchAll = async () => [otherPage];
  events.notificationclick({ notification: { close() {}, data: { url: bookingUrl } }, waitUntil: promise => { pending = promise; } }); await pending;
  assert.deepEqual(navigationOrder, ['focus', 'navigate']); assert.equal(opened.length, 3);
  let intercepted = false;
  events.fetch({ request: { mode: 'cors', url: 'https://staff.example.test/api/v1/grooming/bookings' }, respondWith() { intercepted = true; } });
  assert.equal(intercepted, false);
  const manifest = JSON.parse(await readFile(new URL('../apps/web/public/grooming/manifest.webmanifest', import.meta.url), 'utf8'));
  assert.equal(manifest.scope, '/grooming/'); assert.equal(manifest.start_url, '/grooming/calendar');
});
