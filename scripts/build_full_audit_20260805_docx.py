def add_table(doc: Document, headers: list[str], rows: list[list[str]], widths: list[float] | None = None, font_size=8.6):
    table = doc.add_table(rows=1, cols=len(headers))
    table.autofit = False
    if widths:
        for i, width in enumerate(widths):
            table.columns[i].width = Cm(width)
    for i, title in enumerate(headers):
        shade(table.rows[0].cells[i], NAVY)
        set_cell_text(table.rows[0].cells[i], title, size=font_size, color=WHITE, bold=True)
    repeat_header(table.rows[0])
    for row_index, values in enumerate(rows):
        row = table.add_row()
        keep_row(row)
        for i, value in enumerate(values):
            if row_index % 2 == 1:
                shade(row.cells[i], GRAY_LIGHT)
            set_cell_text(row.cells[i], value, size=font_size)
    return table


def add_status_row(doc: Document, title: str, body: str, fill: str, accent: str) -> None:
    table = doc.add_table(rows=1, cols=2)
    table.autofit = False
    table.columns[0].width = Cm(4.2)
    table.columns[1].width = Cm(12.4)
    shade(table.cell(0, 0), fill)
    shade(table.cell(0, 1), fill)
    set_cell_text(table.cell(0, 0), title, size=9.1, color=accent, bold=True)
    set_cell_text(table.cell(0, 1), body, size=9.1)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)


def add_picture(doc: Document, file_name: str, caption: str, width_cm: float = 16.5) -> None:
    path = SHOT_DIR / file_name
    if not path.exists():
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after = Pt(4)
    p.add_run().add_picture(str(path), width=Cm(width_cm))
    cp = doc.add_paragraph()
    cp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cp.paragraph_format.space_after = Pt(8)
    set_run(cp.add_run(caption), size=8.3, color=MUTED, italic=True)


def add_module(doc: Document, number: str, title: str, verdict: str, exists: list[str], pending: list[str], status_fill: str, status_color: str) -> None:
    add_heading(doc, f"{number}. {title}", 2)
