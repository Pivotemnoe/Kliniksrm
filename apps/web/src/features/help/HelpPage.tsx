export function HelpPage() {
  const navigate = useNavigate();
  const { data } = useCurrentEmployee();
  const employee = data?.employee;
  const [query, setQuery] = useState('');
  const [audience, setAudience] = useState<AudienceFilter>('Все сотрудники');

  const filteredSections = useMemo(() => {
    const normalizedQuery = query.trim().toLocaleLowerCase('ru-RU');
    return guideSections.filter((section) => {
      const audienceMatches = audience === 'Все сотрудники' || section.audiences.includes(audience);
      if (!audienceMatches) {
        return false;
      }
      if (!normalizedQuery) {
        return true;
      }
      const searchable = [
        section.title,
        section.summary,
        ...section.path,
        ...section.steps,
        ...section.checks,
        section.warning ?? '',
      ]
        .join(' ')
        .toLocaleLowerCase('ru-RU');
      return searchable.includes(normalizedQuery);
    });
  }, [audience, query]);

  return (
    <div className="page help-page">
      <PageHeader
        title="Инструкция"
        description="Пошаговая работа в TemichevVet: от входа и приёма до склада, финансов, резервных копий и обновления."
        extra={
          <Space wrap className="help-print-actions">
            <Button icon={<PrinterOutlined />} onClick={() => window.print()}>
              Печать / сохранить PDF
            </Button>
          </Space>
        }
      />

      <Alert
        className="help-intro-alert"
        type="info"
        showIcon
        icon={<ReadOutlined />}
        message="Как пользоваться инструкцией"
        description="Выберите свою роль или найдите действие по слову. В каждом блоке есть путь по меню, порядок действий, проверка результата и предупреждения. При печати сохраняется текущая подборка."
      />

      <div className="help-toolbar">
        <Input
          size="large"
          allowClear
          value={query}
          prefix={<SearchOutlined />}
          placeholder="Например: стационар, оплатить, температура, штрих-код, импорт"
          onChange={(event) => setQuery(event.target.value)}
        />
        <Segmented
          block
          value={audience}
          options={audienceOptions}
          onChange={(value) => setAudience(String(value) as AudienceFilter)}
        />
      </div>

      <div className="help-layout">
        <aside className="help-contents" aria-label="Содержание инструкции">
          <div className="help-contents-title">Содержание</div>
          <Typography.Text type="secondary">Найдено разделов: {filteredSections.length}</Typography.Text>
          <nav>
            {filteredSections.map((section) => (
              <a key={section.id} href={`#${section.id}`}>
                {section.title}
              </a>
            ))}
          </nav>
        </aside>

        <main className="help-guides">
          {filteredSections.length ? (
            filteredSections.map((section) => {
              const routeAvailable = section.route ? canAccessPath(employee, section.route) : false;
              return (
                <Card key={section.id} id={section.id} className="help-guide-card" variant="outlined">
                  <div className="help-guide-heading">
                    <div>
                      <Typography.Title level={3}>{section.title}</Typography.Title>
                      <Typography.Paragraph type="secondary">{section.summary}</Typography.Paragraph>
                    </div>
                    <Space wrap>
                      {section.audiences.map((item) => (
                        <Tag key={item} color={item === 'Врач' ? 'blue' : item === 'Администратор' ? 'cyan' : 'gold'}>
                          {item}
                        </Tag>
                      ))}
                    </Space>
                  </div>

                  <ScreenMap title="Куда нажимать" path={section.path} />

                  <div className="help-guide-columns">
                    <section>
                      <Typography.Title level={4}>Порядок действий</Typography.Title>
                      <ol className="help-step-list">
                        {section.steps.map((step) => (
                          <li key={step}>{step}</li>
                        ))}
                      </ol>
                    </section>
                    <section className="help-check-panel">
                      <Typography.Title level={4}>Как понять, что всё правильно</Typography.Title>
                      <ul>
                        {section.checks.map((check) => (
                          <li key={check}>
                            <CheckCircleOutlined />
                            <span>{check}</span>
                          </li>
                        ))}
                      </ul>
                      {section.warning ? (
                        <Alert
                          type="warning"
                          showIcon
                          icon={<SafetyCertificateOutlined />}
                          message="Важно"
                          description={section.warning}
                        />
                      ) : null}
                    </section>
                  </div>

                  {section.route ? (
                    <div className="help-guide-action">
                      <Button
                        type="primary"
                        ghost
                        icon={<ArrowRightOutlined />}
                        disabled={!routeAvailable}
                        onClick={() => navigate(section.route!)}
                      >
                        {routeAvailable ? section.routeLabel : 'Раздел недоступен вашей роли'}
                      </Button>
                    </div>
                  ) : null}
                </Card>
              );
            })
          ) : (
            <Card className="help-empty-card" variant="outlined">
              <Empty
                description="По вашему запросу раздел не найден"
                image={Empty.PRESENTED_IMAGE_SIMPLE}
              >
                <Button onClick={() => { setQuery(''); setAudience('Все сотрудники'); }}>Показать всю инструкцию</Button>
              </Empty>
            </Card>
          )}
        </main>
      </div>
    </div>
  );
}

function ScreenMap({ title, path }: { title: string; path: string[] }) {
  return (
    <div className="help-screen-map" role="img" aria-label={`${title}: ${path.join(', ')}`}>
      <div className="help-screen-map-bar">
        <span />
        <span />
        <span />
        <strong>{title}</strong>
      </div>
      <div className="help-screen-map-body">
        {path.map((item, index) => (
          <div key={`${item}-${index}`} className="help-screen-map-step">
            <span>{index + 1}</span>
            <strong>{item}</strong>
            {index < path.length - 1 ? <ArrowRightOutlined /> : null}
          </div>
        ))}
      </div>
    </div>
  );
}
